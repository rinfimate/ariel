#!/usr/bin/env node
// Generates TypeScript + C++ bindings (JSI) and WASM bindings from the
// host-native Rust library. Works on Windows (.dll), macOS (.dylib), and
// Linux (.so) by bypassing the prettier/clang-format step that breaks on Windows.

const { execSync } = require('child_process');
const path = require('path');
const os = require('os');
const fs = require('fs');

const root  = path.resolve(__dirname, '..');
const crate = path.join(root, 'rust', 'mermaid_wrapper');

const ext    = os.platform() === 'win32'  ? '.dll'
             : os.platform() === 'darwin' ? '.dylib'
             : '.so';
const prefix = os.platform() === 'win32' ? '' : 'lib';
// Relative to `crate` dir so `cargo metadata` resolves Cargo.toml correctly
const lib = path.join('target', 'debug', `${prefix}mermaid_wrapper${ext}`);

// ── Step 1: Build host-native library ────────────────────────────────────────
console.log('\n[ariel] Building host library…');
execSync('cargo build --manifest-path rust/mermaid_wrapper/Cargo.toml', {
  stdio: 'inherit',
  cwd: root,
});

// ── Step 2: Generate JSI (React Native) bindings ─────────────────────────────
console.log('\n[ariel] Generating JSI bindings…');
execSync(
  `npx uniffi-bindgen-react-native generate jsi bindings --library --no-format --ts-dir ../../src/generated/rn --cpp-dir ../../cpp ${lib}`,
  { stdio: 'inherit', cwd: crate }
);

// Ensure cpp/generated/ exists — ubrn on Linux generates flat files in cpp/ only.
// CMakeLists.txt and cpp/react-native-ariel.cpp both expect cpp/generated/mermaid_wrapper.*
const generatedDir = path.join(root, 'cpp', 'generated');
['mermaid_wrapper.cpp', 'mermaid_wrapper.hpp'].forEach(file => {
  const dest = path.join(generatedDir, file);
  const src  = path.join(root, 'cpp', file);
  if (fs.existsSync(src)) {
    fs.mkdirSync(generatedDir, { recursive: true });
    fs.copyFileSync(src, dest);
    console.log(`[ariel] Copied cpp/${file} → cpp/generated/${file}`);
  }
});

// ── Step 3: Generate turbo-module glue (CMakeLists, Java/Kotlin, iOS podspec) ─
console.log('\n[ariel] Generating turbo-module glue…');
execSync(
  `npx uniffi-bindgen-react-native generate jsi turbo-module --config ubrn.config.yaml mermaid_wrapper`,
  { stdio: 'inherit', cwd: root }
);

// ── Patch ArielModule.kt: use reflection for jsCallInvokerHolder ──────────────
// ubrn generates context.jsCallInvokerHolder which is only available in RN 0.74+.
// Patch to use reflection so the library also builds against RN 0.73.
const arielModuleKt = path.join(root, 'android', 'src', 'main', 'java', 'com', 'ariel', 'ArielModule.kt');
if (fs.existsSync(arielModuleKt)) {
  let kt = fs.readFileSync(arielModuleKt, 'utf8');
  kt = kt.replace(
    /override fun installRustCrate\(\): Boolean \{[\s\S]*?context\.jsCallInvokerHolder!!\s*\)\s*\}/,
    `override fun installRustCrate(): Boolean {
    val context = this.reactApplicationContext
    return nativeInstallRustCrate(
      context.javaScriptContextHolder!!.get(),
      resolveCallInvokerHolder(context)
    )
  }

  private fun resolveCallInvokerHolder(context: ReactApplicationContext): CallInvokerHolder {
    // RN 0.74+ exposes getJSCallInvokerHolder() on ReactContext directly.
    // RN 0.73 only has it on CatalystInstance — use reflection to handle both.
    val direct = context.javaClass.methods.firstOrNull { it.name == "getJSCallInvokerHolder" }
    if (direct != null) return direct.invoke(context) as CallInvokerHolder
    @Suppress("DEPRECATION")
    val ci = checkNotNull(context.catalystInstance) { "No CatalystInstance" }
    return ci.javaClass.methods.first { it.name == "getJSCallInvokerHolder" }.invoke(ci) as CallInvokerHolder
  }`
  );
  fs.writeFileSync(arielModuleKt, kt, 'utf8');
  console.log('[ariel] Patched ArielModule.kt (jsCallInvokerHolder → reflection for RN 0.73 compat)');
}

// ── Write ArielImpl.h stub (needed by autolinking.cpp, not generated by ubrn) ─
const arielImplH = path.join(root, 'android', 'generated', 'jni', 'ArielImpl.h');
fs.mkdirSync(path.dirname(arielImplH), { recursive: true });
if (!fs.existsSync(arielImplH) || fs.readFileSync(arielImplH, 'utf8').includes('kModuleName = ""')) {
  fs.writeFileSync(arielImplH, `#pragma once
#include <ReactCommon/TurboModule.h>
#include <ArielSpec.h>
namespace facebook::react {
class ArielImpl final : public TurboModule {
public:
  static constexpr const char* kModuleName = "Ariel";
  explicit ArielImpl(std::shared_ptr<CallInvoker> jsInvoker)
      : TurboModule("Ariel", std::move(jsInvoker)) {}
};
} // namespace facebook::react
`, 'utf8');
  console.log('[ariel] Wrote android/generated/jni/ArielImpl.h');
}

// ── Step 5: Generate WASM bindings ────────────────────────────────────────────
console.log('\n[ariel] Generating WASM bindings…');
// --cpp-dir for WASM points to the wasm crate src/ so the .rs module lands next to lib.rs
execSync(
  `npx uniffi-bindgen-react-native generate wasm bindings --library --no-format --ts-dir ../../src/generated/web --cpp-dir ../../rust_modules/wasm/src ${lib}`,
  { stdio: 'inherit', cwd: crate }
);

// ── Step 6: Generate WASM crate (Cargo.toml + wasm-bindgen entrypoints) ───────
console.log('\n[ariel] Generating WASM crate…');
execSync(
  `npx uniffi-bindgen-react-native generate wasm wasm-crate --config ubrn.config.yaml mermaid_wrapper`,
  { stdio: 'inherit', cwd: root }
);

// ── Fix android/CMakeLists.txt: correct paths for consumer (npm-installed) use ──
// ubrn generates CMakeLists.txt with CMAKE_SOURCE_DIR (resolves to the app root
// when included as a subproject) and an execute_process node call for uniffi.
// Both break when the library is installed as an npm package by a consumer.
const androidCMake = path.join(root, 'android', 'CMakeLists.txt');
if (fs.existsSync(androidCMake)) {
  let cmake = fs.readFileSync(androidCMake, 'utf8');

  // Fix 1: Replace execute_process(COMMAND node ...) uniffi path resolution with
  // a static dual-path check that works both locally and when npm-hoisted.
  cmake = cmake.replace(
    /# Resolve the path to the uniffi-bindgen-react-native package[\s\S]*?include_directories\(/,
    `# Resolve uniffi-bindgen-react-native includes.
# When building the library locally: ../node_modules/ (workspace root)
# When installed as npm dependency: ../../ (npm hoists to consumer's node_modules)
set(_UNIFFI_LOCAL  "\${CMAKE_CURRENT_LIST_DIR}/../node_modules/uniffi-bindgen-react-native/cpp/includes")
set(_UNIFFI_HOISTED "\${CMAKE_CURRENT_LIST_DIR}/../../uniffi-bindgen-react-native/cpp/includes")
if(EXISTS "\${_UNIFFI_LOCAL}")
  cmake_path(SET UNIFFI_INCLUDES "\${_UNIFFI_LOCAL}" NORMALIZE)
else()
  cmake_path(SET UNIFFI_INCLUDES "\${_UNIFFI_HOISTED}" NORMALIZE)
endif()

include_directories(`
  );

  // Fix 2: Replace leftover ${UNIFFI_BINDGEN_PATH} with ${UNIFFI_INCLUDES}
  cmake = cmake.replace(/\$\{UNIFFI_BINDGEN_PATH\}\/cpp\/includes/g, '${UNIFFI_INCLUDES}');

  // Fix 3: CMAKE_SOURCE_DIR → CMAKE_CURRENT_LIST_DIR for rust lib path
  cmake = cmake.replace(/\$\{CMAKE_SOURCE_DIR\}\/src\/main\/jniLibs/g,
    '${CMAKE_CURRENT_LIST_DIR}/src/main/jniLibs');
  cmake = cmake.replace(/CMAKE_SOURCE_DIR.*?jniLibs/g,
    '${CMAKE_CURRENT_LIST_DIR}/src/main/jniLibs');

  fs.writeFileSync(androidCMake, cmake, 'utf8');
  console.log('[ariel] Patched android/CMakeLists.txt (CMAKE_CURRENT_LIST_DIR, uniffi path)');
}

// ── Fix android/build.gradle: apply com.facebook.react unconditionally ──────
const androidBuildGradle = path.join(root, 'android', 'build.gradle');
if (fs.existsSync(androidBuildGradle)) {
  let gradle = fs.readFileSync(androidBuildGradle, 'utf8');
  // Remove isNewArchitectureEnabled() guard around apply plugin and react block
  gradle = gradle.replace(
    /if \(isNewArchitectureEnabled\(\)\) \{\s*apply plugin: "com\.facebook\.react"\s*\}/,
    'apply plugin: "com.facebook.react"'
  );
  gradle = gradle.replace(
    /if \(isNewArchitectureEnabled\(\)\) \{\s*react \{[\s\S]*?\}\s*\}/,
    `react {\n  jsRootDir = file("../src/")\n  libraryName = "Ariel"\n  codegenJavaPackageName = "com.ariel"\n}`
  );
  // Exclude RN system SOs from the AAR to avoid duplicate-lib conflicts in
  // pre-merged-SO builds (RN 0.73–0.75) where libjsi.so is a standalone file.
  if (!gradle.includes('packagingOptions')) {
    gradle = gradle.replace(
      /\n(repositories\s*\{)/,
      `\nandroid {\n  packagingOptions {\n    excludes += ['lib/*/libjsi.so', 'lib/*/libturbomodulejsijni.so', 'lib/*/libreact_nativemodule_core.so']\n  }\n}\n\n$1`
    );
  }
  fs.writeFileSync(androidBuildGradle, gradle, 'utf8');
  console.log('[ariel] Patched android/build.gradle (unconditional react plugin)');
}

// Fix Ariel.podspec: backslashes in source_files glob and wrong repo URL
const podspec = path.join(root, 'Ariel.podspec');
if (fs.existsSync(podspec)) {
  let spec = fs.readFileSync(podspec, 'utf8');
  // Remove redundant backslash glob patterns (ios/** and cpp/** already cover subdirs)
  spec = spec.replace(/,\s*"ios\\generated\/\*\*\/[^"]*"/g, '');
  spec = spec.replace(/,\s*"cpp\\generated\/\*\*\/[^"]*"/g, '');
  // Fix repo URL if ubrn wrote the wrong one
  spec = spec.replace(/github\.com\/rinfi\/ariel/, 'github.com/rinfimate/ariel');
  fs.writeFileSync(podspec, spec, 'utf8');
}

// Fix Windows backslashes in cpp/react-native-ariel.cpp include paths (breaks macOS compilation)
const cppEntry = path.join(root, 'cpp', 'react-native-ariel.cpp');
if (fs.existsSync(cppEntry)) {
  const fixed = fs.readFileSync(cppEntry, 'utf8').replace(/generated\\mermaid_wrapper/g, 'generated/mermaid_wrapper');
  fs.writeFileSync(cppEntry, fixed, 'utf8');
}

// ── Fix mermaid_wrapper.cpp: add missing <unordered_map> include ──────────────
// NDK 25 (RN 0.73) does not include <unordered_map> transitively; NDK 26+ does.
for (const cppFile of [
  path.join(root, 'cpp', 'generated', 'mermaid_wrapper.cpp'),
  path.join(root, 'cpp', 'mermaid_wrapper.cpp'),
]) {
  if (fs.existsSync(cppFile)) {
    let cpp = fs.readFileSync(cppFile, 'utf8');
    if (cpp.includes('unordered_map') && !cpp.includes('#include <unordered_map>')) {
      cpp = cpp.replace('#include <map>', '#include <map>\n#include <unordered_map>');
      fs.writeFileSync(cppFile, cpp, 'utf8');
      console.log(`[ariel] Patched ${path.relative(root, cppFile)} (added <unordered_map>)`);
    }
  }
}

// Fix Windows backslashes in all generated files (Metro and Cargo can't handle them)

const webIndex = path.join(root, 'src', 'index.web.ts');
if (fs.existsSync(webIndex)) {
  let src = fs.readFileSync(webIndex, 'utf8');
  // Fix Windows backslashes in import paths
  src = src.replace(/'\.\/(generated\\[^']+)'/g, (_, p) => `'./${p.replace(/\\/g, '/')}'`);
  // wasm-pack names the output after the crate (react_native_ariel), not "index"
  src = src.replace(/wasm-bindgen\/index\.js/g, 'wasm-bindgen/react_native_ariel.js');
  src = src.replace(/wasm-bindgen\/index_bg\.wasm/g, 'wasm-bindgen/react_native_ariel_bg.wasm');
  fs.writeFileSync(webIndex, src, 'utf8');
}

// Fix src/index.tsx (turbo-module entry) backslash paths
const nativeIndex = path.join(root, 'src', 'index.tsx');
if (fs.existsSync(nativeIndex)) {
  const fixed = fs.readFileSync(nativeIndex, 'utf8').replace(/generated\\rn/g, 'generated/rn');
  fs.writeFileSync(nativeIndex, fixed, 'utf8');
}

// Same fix for the generated WASM TypeScript bindings
const webBindings = path.join(root, 'src', 'generated', 'web', 'mermaid_wrapper.ts');
if (fs.existsSync(webBindings)) {
  let src = fs.readFileSync(webBindings, 'utf8');
  src = src.replace(/wasm-bindgen\/index\.js/g, 'wasm-bindgen/react_native_ariel.js');
  src = src.replace(/wasm-bindgen\/index_bg\.wasm/g, 'wasm-bindgen/react_native_ariel_bg.wasm');
  fs.writeFileSync(webBindings, src, 'utf8');
}

const wasmCargo = path.join(root, 'rust_modules', 'wasm', 'Cargo.toml');
if (fs.existsSync(wasmCargo)) {
  let cargo = fs.readFileSync(wasmCargo, 'utf8');
  // Convert absolute Windows path for uniffi-runtime-javascript to a relative forward-slash path
  cargo = cargo.replace(
    /path = ".*?uniffi-runtime-javascript"/,
    'path = "../../node_modules/uniffi-bindgen-react-native/crates/uniffi-runtime-javascript"'
  );
  // Convert any remaining backslash paths to forward slashes
  cargo = cargo.replace(/path = "([^"]+)"/g, (_, p) => `path = "${p.replace(/\\/g, '/')}"`);
  fs.writeFileSync(wasmCargo, cargo, 'utf8');
}

// ── Append custom JS-layer exports to index.web.ts ───────────────────────────
// ubrn regenerates this file and wipes any manual additions, so we re-append
// them here every time codegen runs.
if (fs.existsSync(webIndex)) {
  let src = fs.readFileSync(webIndex, 'utf8');
  const customExports = [
    "export { useArielTheme } from './useArielTheme.web';",
    "export { ArielThemeRegistry } from './ArielThemeRegistry.web';",
    "export { ArielLightTheme, ArielDarkTheme } from './themes';",
  ];
  let changed = false;
  for (const line of customExports) {
    if (!src.includes(line)) {
      src += `\n${line}`;
      changed = true;
    }
  }
  if (changed) {
    fs.writeFileSync(webIndex, src, 'utf8');
    console.log('[ariel] Appended custom exports to src/index.web.ts');
  }
}

// Same for src/index.tsx (native)
if (fs.existsSync(nativeIndex)) {
  let src = fs.readFileSync(nativeIndex, 'utf8');
  const customExports = [
    "export { useArielTheme } from './useArielTheme';",
    "export { ArielThemeRegistry } from './ArielThemeRegistry';",
    "export { ArielLightTheme, ArielDarkTheme } from './themes';",
  ];
  let changed = false;
  for (const line of customExports) {
    if (!src.includes(line)) {
      src += `\n${line}`;
      changed = true;
    }
  }
  if (changed) {
    fs.writeFileSync(nativeIndex, src, 'utf8');
    console.log('[ariel] Appended custom exports to src/index.tsx');
  }
}

console.log('\n[ariel] Done — bindings written to src/generated/rn/, src/generated/web/, and cpp/');
